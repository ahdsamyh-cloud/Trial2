/**
 * Reports in the department's OWN formats. A user uploads an Excel (.xlsx) or Word (.docx) file
 * containing placeholders; the system fills it with live data for a week or a month.
 *
 *   {{report.period}}             a single value (see fields())
 *   {{lit.hearings.date}}         Excel: a row with list placeholders is repeated once per item
 *   {{#lit.hearings}} {{date}} {{reference}} {{/lit.hearings}}   Word: a repeated block / table row
 *
 * Formats change often, so nothing about a format is built into the system: upload a new file.
 * Data follows the requester's access (restricted matters, unit scope); management (aggregate-only
 * access) gets totals, never lists of matters.
 */
type Period = 'WEEKLY' | 'MONTHLY';
type Row = Record<string, string | number>;
type ReportData = Record<string, unknown>;

const TZ = 'Indian/Maldives';
const MVT = 5 * 3600_000;
const fmtD = (d?: Date | null) => (d ? new Intl.DateTimeFormat('en-GB', { timeZone: TZ, day: '2-digit', month: 'short', year: 'numeric' }).format(d) : '');
const fmtDT = (d?: Date | null) => (d ? new Intl.DateTimeFormat('en-GB', { timeZone: TZ, day: '2-digit', month: 'short', year: 'numeric', hour: '2-digit', minute: '2-digit' }).format(d) : '');
const nice = (s?: string | null) => (s ? s.replace(/_/g, ' ').toLowerCase().replace(/^\w/, (c) => c.toUpperCase()) : '');
/** Same protection as list exports: text that Excel could treat as a formula is prefixed. */
const safeText = (v: string) => (/^[=+\-@\t\r]/.test(v) ? `'${v}` : v);

