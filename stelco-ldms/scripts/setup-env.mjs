#!/usr/bin/env node
// Creates the two git-ignored local config files with fresh random secrets (any OS):
//   infra/.env     passwords for the dev Docker services (Postgres, MinIO)
//   apps/api/.env  API settings for local development, matching infra/.env
// Existing files are never overwritten. Nothing here is suitable for production
// (see docs/IT_SETUP.md for that).
import { randomBytes } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const infraEnv = join(root, 'infra', '.env');
const apiEnv = join(root, 'apps', 'api', '.env');
const testEnv = join(root, 'apps', 'api', '.env.test');

const hex = (n) => randomBytes(n).toString('hex'); // URL-safe, no escaping needed in connection strings
const b64 = (n) => randomBytes(n).toString('base64');
const base32 = (buf) => {
  const A = 'ABCDEFGHIJKLMNOPQRSTUVWXYZ234567';
  let bits = '';
  for (const b of buf) bits += b.toString(2).padStart(8, '0');
  return bits.match(/.{1,5}/g).map((c) => A[parseInt(c.padEnd(5, '0'), 2)]).join('');
};
const parse = (file) => Object.fromEntries(
  readFileSync(file, 'utf8').split(/\r?\n/).filter((l) => l && !l.startsWith('#') && l.includes('='))
    .map((l) => [l.slice(0, l.indexOf('=')).trim(), l.slice(l.indexOf('=') + 1).trim()]),
);

/**
 * Atomically create `file` (owner-only permissions) unless it already exists. Uses the exclusive
 * 'wx' flag instead of exists-then-write, so there is no window in which a file could appear (or be
 * swapped for a link) between the check and the write, and an existing file is never overwritten.
 * Returns true if created, false if it was already there.
 */
function createOnce(file, lines, label) {
  try {
    writeFileSync(file, lines.join('\n'), { flag: 'wx', mode: 0o600 });
    console.log(`Created ${label}`);
    return true;
  } catch (err) {
    if (err.code !== 'EEXIST') throw err;
    console.log(`${label} already exists - keeping it.`);
    return false;
  }
}

// 1) Docker service passwords (reuse if the file already exists, so all files stay in sync).
let infra = { DEV_POSTGRES_PASSWORD: hex(24), DEV_APP_DB_PASSWORD: hex(24), DEV_MINIO_ROOT_PASSWORD: hex(24) };
if (!createOnce(infraEnv, [
  '# Local development only (git-ignored). Generated by `pnpm setup:env`.',
  ...Object.entries(infra).map(([k, v]) => `${k}=${v}`), '',
], 'infra/.env')) infra = parse(infraEnv);
for (const k of ['DEV_POSTGRES_PASSWORD', 'DEV_APP_DB_PASSWORD']) {
  if (!infra[k]) { console.error(`infra/.env has no ${k}. Fix it or delete the file and run again.`); process.exit(1); }
}

// 2) API settings.
{
  const demoPassword = `Ldms-${randomBytes(12).toString('base64url')}`;
  const totp = base32(randomBytes(20));
  const env = {
    NODE_ENV: 'development',
    PORT: '4000',
    APP_ORIGIN: 'http://localhost:3000',
    COOKIE_SECURE: 'false',
    TRUST_PROXY: '1',
    DATABASE_URL: `postgresql://ldms_app:${infra.DEV_APP_DB_PASSWORD}@localhost:5432/ldms`,
    MIGRATION_DATABASE_URL: `postgresql://ldms_owner:${infra.DEV_POSTGRES_PASSWORD}@localhost:5432/ldms`,
    REDIS_URL: 'redis://localhost:6379',
    FIELD_KEYS: `k1:${b64(32)}`,
    FIELD_KEY_ACTIVE: 'k1',
    SIGNING_KEY: b64(48),
    STORAGE_DRIVER: 'fs',
    STORAGE_FS_ROOT: './var/storage',
    AV_MODE: 'clamd',
    CLAMD_HOST: 'localhost',
    CLAMD_PORT: '3310',
    // Mailpit (from compose.dev.yml) catches all email: open http://localhost:8025
    SMTP_ENABLED: 'true',
    SMTP_HOST: 'localhost',
    SMTP_PORT: '1025',
    SMTP_REQUIRE_TLS: 'false',
    // Run background jobs inside the API so no separate worker is needed for a local trial.
    QUEUE_INLINE: 'true',
    OCR_ENABLED: 'false',
    LOG_LEVEL: 'info',
    SEED_DEMO: 'true',
    DEMO_PASSWORD: demoPassword,
    DEMO_TOTP_SECRET: totp,
  };
  createOnce(apiEnv, [
    '# Local development only (git-ignored). Generated by `pnpm setup:env`. NEVER use these values in production.',
    ...Object.entries(env).map(([k, v]) => `${k}=${v}`), '',
  ], 'apps/api/.env');
}
// 3) Integration-test settings: the separate ldms_test database (created by infra/postgres/init-dev.sh).
//    The test run wipes and re-seeds that database every time; your dev data in `ldms` is untouched.
createOnce(testEnv, [
  '# Integration tests only (git-ignored). Generated by `pnpm setup:env`. The run WIPES this database.',
  `DATABASE_URL=postgresql://ldms_app:${infra.DEV_APP_DB_PASSWORD}@localhost:5432/ldms_test`,
  `MIGRATION_DATABASE_URL=postgresql://ldms_owner:${infra.DEV_POSTGRES_PASSWORD}@localhost:5432/ldms_test`,
  'REDIS_URL=redis://localhost:6379/5', '',
], 'apps/api/.env.test');
// SECURITY: secrets are never printed (terminal scrollback and CI logs are not a safe place for them).
console.log('\nDemo login: every demo user (hod, uh.lit, lo.lit1, ...) uses the password in the DEMO_PASSWORD line');
console.log('of apps/api/.env (open it in Notepad, or: findstr DEMO_PASSWORD apps\\api\\.env  /  grep DEMO_PASSWORD apps/api/.env).');
console.log('For the 6-digit code run `pnpm demo:code`, or add DEMO_TOTP_SECRET from the same file to an authenticator app.');
console.log('Next: docker compose -f infra/compose.dev.yml up -d   then   pnpm setup:db   then   pnpm dev');
